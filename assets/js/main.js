// 处理脚注的返回链接
document.addEventListener("DOMContentLoaded", function () {

  // 先把 callout 内的脚注搬到页面底部的全局脚注区域
  relocateCalloutFootnotes();

  initShareWidgets();

  // 修复可能存在的 ID 问题
  fixFootnoteIds();

  // Hash navigation, including footnotes, is handled by the delegated
  // listener in layouts/partials/head/js.html.
});

// 修复脚注 ID 相关问题
function fixFootnoteIds() {
  // 检查并修复脚注引用 ID
  const footnoteRefs = document.querySelectorAll('sup[id^="fnref"]');
  footnoteRefs.forEach((ref) => {
    const id = ref.id;
    const link = ref.querySelector("a");
    if (link) {
      const href = link.getAttribute("href");
      if (href) {
        // 确保链接指向正确的脚注
        const targetId = href.substring(1);
        const target = document.getElementById(targetId);
        if (target) {
          // 确保脚注返回链接指向正确的引用
          const backref = target.querySelector(".footnote-backref");
          if (backref) {
            backref.setAttribute("href", "#" + id);
            console.log(
              `修复脚注返回链接: ${backref.getAttribute("href")} 指向 ${id}`
            );
          }
        }
      }
    }
  });
}

// 将 callout 中生成的脚注节点合并到页面底部的统一脚注列表
function relocateCalloutFootnotes() {
  const calloutFootnoteBlocks = Array.from(document.querySelectorAll('.callout .footnotes'));
  if (calloutFootnoteBlocks.length === 0) return;

  // 全局脚注容器（不在 callout 中）
  let globalFootnotes = Array.from(document.querySelectorAll('.footnotes'))
    .find(el => !el.closest('.callout'));

  // 文章内容容器（用于新建全局脚注时的插入位置）
  const contentRoot = document.querySelector('article .p-8.prose') || document.querySelector('.p-8.prose');

  if (!globalFootnotes) {
    // 创建全局脚注容器
    globalFootnotes = document.createElement('div');
    globalFootnotes.className = 'footnotes';
    const hr = document.createElement('hr');
    const ol = document.createElement('ol');
    globalFootnotes.appendChild(hr);
    globalFootnotes.appendChild(ol);
    if (contentRoot) {
      contentRoot.appendChild(globalFootnotes);
    } else {
      document.body.appendChild(globalFootnotes);
    }
  }

  const globalList = globalFootnotes.querySelector('ol') || (function(){
    const ol = document.createElement('ol');
    globalFootnotes.appendChild(ol);
    return ol;
  })();

  // 逐个搬运 callout 内的 <li>
  calloutFootnoteBlocks.forEach(block => {
    const list = block.querySelector('ol');
    if (!list) return;
    Array.from(list.children).forEach(li => {
      globalList.appendChild(li); // 保留原有 id，避免锚点失效
    });
    // 移除空容器
    block.remove();
  });
}

function initShareWidgets() {
  const widgets = document.querySelectorAll("[data-share-widget]");
  if (widgets.length === 0) return;

  widgets.forEach((widget) => {
    const copySummaryButton = widget.querySelector("[data-share-copy-summary]");
    const label = widget.querySelector("[data-share-label]");
    const shareData = {
      title: widget.dataset.shareTitle || document.title,
      text: widget.dataset.shareText || "",
      url: widget.dataset.shareUrl || window.location.href,
    };
    const shareSummary = [shareData.title, shareData.text, shareData.url]
      .filter(Boolean)
      .join("\n");
    const messages = {
      defaultLabel: widget.dataset.shareLabelDefault || "Share",
      successLabel: widget.dataset.shareLabelSuccess || "Copied",
      copyFailed: widget.dataset.shareCopyFailed || "Copy failed.",
    };
    let feedbackTimer = null;

    const setButtonState = (message, isError = false) => {
      if (!copySummaryButton || !label) return;
      label.textContent = message;
      copySummaryButton.classList.toggle("is-error", isError);
      copySummaryButton.classList.toggle("is-success", !isError && message === messages.successLabel);

      if (feedbackTimer) window.clearTimeout(feedbackTimer);
      feedbackTimer = window.setTimeout(() => {
        label.textContent = messages.defaultLabel;
        copySummaryButton.classList.remove("is-error", "is-success");
      }, 1600);
    };

    if (copySummaryButton) {
      copySummaryButton.addEventListener("click", async () => {
        try {
          await copyToClipboard(shareSummary);
          setButtonState(messages.successLabel);
          copySummaryButton.blur();
        } catch (_) {
          setButtonState(messages.copyFailed, true);
        }
      });
    }
  });
}

async function copyToClipboard(text) {
  if (navigator.clipboard && navigator.clipboard.writeText) {
    await navigator.clipboard.writeText(text);
    return;
  }
  fallbackCopyText(text);
}

function fallbackCopyText(text) {
  const textarea = document.createElement("textarea");
  textarea.value = text;
  textarea.setAttribute("readonly", "");
  textarea.style.position = "absolute";
  textarea.style.left = "-9999px";
  document.body.appendChild(textarea);
  textarea.select();
  document.execCommand("copy");
  document.body.removeChild(textarea);
}
